public class Switch {
    public static void main(String[] args) {
        int i = 3;
        switch(i){
            case 1:
               System.out.println("First statement");
               break;
            case 2:
               System.out.println("Second statement");
               break;
            case 3:
               System.out.println("Third statement");
               break;
            default:
                System.out.println("Default statement");
                break;


        }
    }
    
}
